#!/usr/bin/env bash
# Render prod docker-stack.yml.j2 from inventory.yml.example (or inventory.yml)
# and assert cutover invariants. Read-only. No SSH / no Swarm apply.
#
# Usage (repo root or any cwd):
#   ./LENR_SIM_APP_v2/infrastructure/scripts/swarm-039-assert-prod-stack-render.sh
# Env:
#   STACK_RENDER_OUT  optional path for rendered YAML (default: temp + copy to
#                     STAGING_EVIDENCE_DIR or /opt/cursor/artifacts when writable)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
ANSIBLE_DIR="${ROOT}/LENR_SIM_APP_v2/infrastructure/ansible"
CI_IP="${CI_IP:-45.93.100.251}"

need() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: missing $1" >&2; exit 2; }; }
need ansible-playbook

if [[ -n "${STAGING_EVIDENCE_DIR:-}" ]]; then
  EVIDENCE_DIR="$STAGING_EVIDENCE_DIR"
elif [[ -d /opt/cursor/artifacts && -w /opt/cursor/artifacts ]]; then
  EVIDENCE_DIR="/opt/cursor/artifacts"
else
  EVIDENCE_DIR="${ROOT}/.staging-evidence"
fi
mkdir -p "$EVIDENCE_DIR"

stack_out="${STACK_RENDER_OUT:-$EVIDENCE_DIR/docker-stack-prod-render.yml}"
prod_inv="$(mktemp -t prod-inv.XXXXXX.yml)"
stack_tmp="$(mktemp -t docker-stack-prod.XXXXXX.yml)"
render_pb="${ANSIBLE_DIR}/playbooks/.ci-render-prod-stack.yml"
cleanup() { rm -f "$prod_inv" "$stack_tmp" "$render_pb"; }
trap cleanup EXIT

if [[ -f "${ANSIBLE_DIR}/inventory.yml" ]]; then
  cp "${ANSIBLE_DIR}/inventory.yml" "$prod_inv"
else
  cp "${ANSIBLE_DIR}/inventory.yml.example" "$prod_inv"
fi

if grep -vE '^[[:space:]]*#' "$prod_inv" | grep -qE "${CI_IP//./\\.}|2012566"; then
  echo "ERROR: prod inventory lists CI node — refuse" >&2
  exit 1
fi

cat >"$render_pb" <<'EOF'
---
# Local-only render of docker-stack.yml.j2 for cutover invariant gates (no SSH).
# Generated by swarm-039-assert-prod-stack-render.sh; not committed.
- hosts: swarm_managers
  connection: local
  gather_facts: false
  become: false
  tasks:
    - name: Render production Docker stack from inventory host vars
      ansible.builtin.template:
        src: ../templates/docker-stack.yml.j2
        dest: "{{ stack_render_dest }}"
      run_once: true
EOF

(
  cd "$ANSIBLE_DIR"
  ansible-playbook -i "$prod_inv" -c local \
    -e "stack_render_dest=$stack_tmp" \
    "$render_pb"
)

fail=0
grep -q 'node.labels.postgres == true' "$stack_tmp" \
  || { echo "FAIL: missing postgres placement constraint"; fail=1; }
grep -q 'name: "lenr-sim_postgres_data"' "$stack_tmp" \
  || { echo "FAIL: missing external volume name lenr-sim_postgres_data"; fail=1; }
grep -q 'external: true' "$stack_tmp" \
  || { echo "FAIL: postgres_data volume not marked external"; fail=1; }
grep -qF 'PathPrefix(`/api`)' "$stack_tmp" \
  || { echo "FAIL: missing SPA/API PathPrefix(`/api`) router rule"; fail=1; }
grep -qF 'Host(`lenr-sim-beta.conscious.energy`)' "$stack_tmp" \
  || { echo "FAIL: missing SPA host lenr-sim-beta.conscious.energy"; fail=1; }
grep -qE 'lenr-sim-frontend|routers\.frontend' "$stack_tmp" \
  || { echo "FAIL: frontend/SPA service missing from render"; fail=1; }

if [[ "$fail" -ne 0 ]]; then
  echo "ERROR: prod stack render invariants failed — see $stack_tmp" >&2
  exit 1
fi

cp -f "$stack_tmp" "$stack_out"
echo "OK: prod stack render invariants (postgres pin, external volume, SPA PathPrefix)"
echo "rendered_stack=$stack_out"
